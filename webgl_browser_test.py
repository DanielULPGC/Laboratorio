from pathlib import Path
from playwright.sync_api import sync_playwright
import json, sys
root=Path(__file__).resolve().parent
checks=[];errors=[]
def ck(name, condition):checks.append({'name':name,'pass':bool(condition)})
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content((root/'index.html').read_text(encoding='utf-8'),wait_until='domcontentloaded')
 page.wait_for_timeout(900)
 label=page.locator('#engineStatus').inner_text()
 ck('WebGL2 local inicializado', 'WebGL2 local' in label)
 ck('Contexto gráfico con versión válida', page.evaluate('!!glRenderer && !!glRenderer.gl.getParameter(glRenderer.gl.VERSION)'))
 ck('Malla con triángulos procedurales', page.evaluate('!!glRenderer && glRenderer.geometryTriangles>1500'))
 ck('Fotogramas producidos', page.evaluate('!!glRenderer && glRenderer.getFrames()>4'))
 ck('Lienzo 3D visible',page.locator('#three').is_visible() and page.locator('#view').is_hidden())
 page.screenshot(path=str(root/'captura_webgl_escritorio.png'),full_page=False)
 a=page.evaluate('state.angle');page.locator('#right').click();page.wait_for_timeout(150)
 ck('Cámara giratoria',page.evaluate('state.angle')!=a)
 page.locator('#answer').select_option('down');page.locator('#predict').click();page.locator('#observe').click()
 page.wait_for_timeout(2650)
 ck('Compuertas terminan apertura', page.evaluate('state.opening')>=.999)
 ck('Interbloqueo autoriza ascenso abierto', page.locator('#run').is_enabled())
 page.screenshot(path=str(root/'captura_webgl_compuertas.png'),full_page=False)
 page.locator('#run').click();page.wait_for_timeout(500)
 ck('Robot asciende en GPU',page.evaluate('state.lift>0'))
 ck('No reinicia otro ensayo en curso',page.locator('#run').is_disabled())
 page.screenshot(path=str(root/'captura_webgl_ascenso.png'),full_page=False)
 page.locator('#pixelBtn').click();page.wait_for_timeout(180)
 ck('Modo pixelado Canvas disponible', page.locator('#view').is_visible() and page.locator('#three').is_hidden() and page.evaluate('state.pixel'))
 page.locator('#pixelBtn').click();page.wait_for_timeout(180)
 ck('Regreso real a WebGL',page.locator('#three').is_visible() and page.evaluate('active3D'))
 ck('Comparación documental cargada',page.locator('#references').count()==1 and page.locator('#rubric').count()==1)
 ck('No hubo errores de ejecución',not errors)
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 mobile.on('pageerror',lambda e:errors.append(str(e)))
 mobile.set_content((root/'index.html').read_text(encoding='utf-8'),wait_until='domcontentloaded');mobile.wait_for_timeout(450)
 ck('WebGL2 también inicia en móvil simulado','WebGL2 local' in mobile.locator('#engineStatus').inner_text())
 ck('Vista móvil sin desbordamiento horizontal', mobile.evaluate('document.documentElement.scrollWidth<=innerWidth'))
 mobile.screenshot(path=str(root/'captura_webgl_movil.png'))
 ck('Sin excepciones JavaScript en ambos tamaños',not errors)
 browser.close()
out={'passed':sum(t['pass'] for t in checks),'total':len(checks),'cases':checks,'errors':errors}
(root/'resultado_webgl.json').write_text(json.dumps(out,indent=2,ensure_ascii=False),encoding='utf-8')
print(json.dumps(out,ensure_ascii=False,indent=2))
if out['passed']!=out['total']:sys.exit(1)
